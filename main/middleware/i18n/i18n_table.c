const char *i18n_table_get(hmi_language_t language, i18n_key_t key)
{
    if (((uint32_t)language >= (uint32_t)HMI_LANGUAGE_COUNT) ||
        ((uint32_t)key >= (uint32_t)I18N_KEY_COUNT)) {
        return "";
    }

    return g_i18n_table[(uint32_t)language][(uint32_t)key];
}
